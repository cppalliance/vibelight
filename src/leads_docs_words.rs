/// Tells whether a lowercase word is a stopword.
pub(crate) fn is_stopword(word: &str) -> bool {
    STOPWORDS.binary_search(&word).is_ok()
}

/// Returns a lowercase word without a plural `s`, so that `args` and
/// `arg` compare equal; a word of three letters or fewer, or one that ends
/// in `ss`, stays as it is.
pub(crate) fn singular(word: &str) -> String {
    let plural = word.len() > 3 && word.ends_with('s') && !word.ends_with("ss");
    let single = if plural {
        &word[..word.len() - 1]
    } else {
        word
    };
    single.to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_stopwords_are_sorted_for_their_binary_search() {
        assert!(STOPWORDS.windows(2).all(|w| w[0] < w[1]));
        assert!(is_stopword("the") && !is_stopword("parser"));
        assert_eq!(singular("args"), "arg");
        assert_eq!(singular("class"), "class");
        assert_eq!(singular("its"), "its");
    }
}
