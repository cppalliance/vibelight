/// Tells whether a name is one of the `std` names that docs write.
pub(crate) fn is_std_name(name: &str) -> bool {
    STD_NAMES.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_std_names_are_sorted_for_their_binary_search() {
        assert!(STD_NAMES.windows(2).all(|w| w[0] < w[1]));
        assert!(is_std_name("HashMap") && !is_std_name("Parser"));
    }
}
